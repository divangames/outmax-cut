const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const root = process.cwd();
const url = process.env.OUTMAX_URL || 'http://127.0.0.1:8766';
(async () => {
  const browser = await chromium.launch({headless:process.env.OUTMAX_HEADLESS === '1'});
  const page = await browser.newPage({viewport:{width:1340,height:1000}});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  try {
    await page.goto(url);
    await page.evaluate(()=>document.fonts.ready);
    assert.equal(await page.getByLabel('Битрейт видео',{exact:true}).inputValue(),'2500');
    await page.screenshot({path:path.join(root,'analysis/bitrate-desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.screenshot({path:path.join(root,'analysis/bitrate-mobile.png'),fullPage:true});
    await page.setViewportSize({width:1340,height:1000});
    await page.getByLabel('Битрейт видео',{exact:true}).selectOption('1500');
    assert.equal((await page.locator('#sizeMetric').textContent()).replace(',','.'),'4.29');
    await page.getByRole('button',{name:'Пакетная сборка',exact:true}).click();
    await page.locator('#folderInput').setInputFiles(path.join(root,'видео'));
    await page.waitForFunction(()=>document.querySelectorAll('.batch-row').length===2,null,{timeout:180000});
    console.log('Imported two product folders.');
    const rows=page.locator('.batch-row');
    await rows.nth(0).locator('.batch-item-open').click();
    assert.equal(await page.locator('#bitrate').inputValue(),'2500');
    await page.locator('#bitrate').selectOption('500');
    await rows.nth(1).locator('.batch-item-open').click();
    assert.equal(await page.locator('#bitrate').inputValue(),'2500');
    await rows.nth(0).locator('.batch-item-open').click();
    assert.equal(await page.locator('#bitrate').inputValue(),'500');
    await page.getByRole('button',{name:'Один ролик',exact:true}).click();
    assert.equal(await page.locator('#bitrate').inputValue(),'1500');
    await page.getByRole('button',{name:'Пакетная сборка',exact:true}).click();
    assert.equal(await page.locator('#bitrate').inputValue(),'500');
    await page.locator('#batchOutputPath').fill(path.join(root,'analysis/bitrate-output'));
    await page.locator('#batchRenderButton').click();
    console.log('Rendering two products at 500 and 2500 kbit/s.');
    await page.locator('#batchCancelButton').waitFor();
    assert(await page.locator('#bitrate').isDisabled());
    await page.locator('#batchCancelButton').waitFor({state:'hidden',timeout:600000});
    assert.match(await page.locator('#batchSummary').textContent(),/Сохранено 2 роликов/);
    const reports=fs.readdirSync(path.join(root,'analysis/bitrate-output'),{recursive:true})
      .filter(p=>p.endsWith('.json')).map(p=>JSON.parse(fs.readFileSync(path.join(root,'analysis/bitrate-output',p),'utf8')));
    assert(reports.some(r=>r.settings.bitrate_kbps===500));
    assert(reports.some(r=>r.settings.bitrate_kbps===2500));
    for (const report of reports) assert.equal(report.frames,658);
    await rows.nth(1).locator('.batch-item-open').click();
    await page.locator('#mainVideo').evaluate(v=>v.pause());
    await page.screenshot({path:path.join(root,'analysis/bitrate-result.png'),fullPage:true});
    await page.locator('#bitrate').selectOption('1000');
    assert(await page.locator('#resultActions').isHidden());
    await page.locator('#applySettingsButton').click();
    await rows.nth(0).locator('.batch-item-open').click();
    assert.equal(await page.locator('#bitrate').inputValue(),'1000');
    await page.route('**/api/updates',route=>route.fulfill({json:{status:'available',current:'1.3.0',latest:'1.4.0',size:100000000}}));
    await page.locator('#updatesButton').click();
    await page.getByRole('button',{name:'Скачать обновление',exact:true}).waitFor();
    await page.route('**/api/updates/check',route=>route.fulfill({status:503,json:{error:'Нет подключения к GitHub'}}));
    await page.getByRole('button',{name:'Проверить снова'}).click();
    await page.getByText('Нет подключения к GitHub',{exact:true}).waitFor();
    assert.deepEqual(errors,[]);
    console.log('PASS: bitrate defaults, metrics, independent batch settings, real exports at 500/2500, locks, stale output, apply-to-all, update availability/error and responsive layout.');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
